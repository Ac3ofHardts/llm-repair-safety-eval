#!/usr/bin/env python3
"""Generate the paper's results tables and numeric macros from a results directory.

Usage:
  python3 analysis/make_tables.py                    # results/base   -> paper/tables/
  python3 analysis/make_tables.py --tag archive/m2   # the frozen Milestone 2 results
  python3 analysis/make_tables.py --tag t08 --out paper/tables/t08

Writes (each file starts with a "generated, do not edit" header):
  baseline.tex   Table: security warnings and MISRA violations before repair
  technique.tex  Table: counts by technique
  model.tex      Table: counts by model and technique
  task.tex       Table*: fixed / safety / joint by task and technique
  macros.tex     \\stat{key} values for numbers used in the prose, e.g. \\stat{fixed-pct}

Every number in the paper should come from one of these files, so re-running the
experiment and `make tables` updates the paper without hand-copying.
"""
import argparse
import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "harness"))
from common import RESULTS, ROOT, load_config  # noqa: E402

TECH_NAMES = {"T1": "T1 plain", "T2": "T2 security", "T3": "T3 analyzer", "T4": "T4 safety-aware"}
MODEL_NAMES = {"qwen2.5-coder:32b": "Qwen2.5-Coder 32B", "codestral:22b": "Codestral 22B"}
EXCLUDE_MODELS = {"fake", "oracle", "mock:latest"}


def truthy(v):
    return str(v).strip().lower() == "true"


def n(rows, key):
    return sum(truthy(r[key]) for r in rows)


def pct(a, b):
    return 0 if b == 0 else round(100 * a / b)


def header(src):
    return (f"% GENERATED by analysis/make_tables.py from {src} -- do not edit by hand.\n"
            f"% Re-run `make tables` after changing results.\n")


def baseline_table(base):
    def fmt(m):
        return ", ".join(f"{r}$\\times${c}" for r, c in sorted(m.items())) or "--"

    rows = []
    for tid in sorted(base, key=lambda t: (t[0], int(t[1:]))):
        b = base[tid]
        rows.append(f"        {tid} & {len(b['original']['sec_warnings'])} & {len(b['seeded']['sec_warnings'])} & "
                    f"{fmt(b['original']['misra'])} & {fmt(b['seeded']['misra'])} & "
                    f"{fmt(b.get('upstream_fix_introduces_misra', {}))} \\\\")
    return "\n".join([
        r"\begin{table}[t]",
        r"    \centering",
        r"    \caption{Baseline before repair: security warnings and MISRA subset violations in the original (upstream) and seeded functions}",
        r"    \label{tab:baseline}",
        r"    \footnotesize",
        r"    \resizebox{\linewidth}{!}{%",
        r"    \begin{tabular}{|c|c|c|l|l|l|}",
        r"        \hline",
        r"        \textbf{Task} & \multicolumn{2}{c|}{\textbf{Sec. warnings}} & \multicolumn{2}{c|}{\textbf{MISRA subset}} & \textbf{Upstream fix} \\",
        r"        & \textbf{Orig.} & \textbf{Seeded} & \textbf{Original} & \textbf{Seeded} & \textbf{introduces} \\",
        r"        \hline", *rows, r"        \hline",
        r"    \end{tabular}}",
        r"\end{table}", ""])


def technique_table(rows):
    by = defaultdict(list)
    for r in rows:
        by[r["technique"]].append(r)
    techs = sorted(by)
    per = {len(v) for v in by.values()}
    n_per = per.pop() if len(per) == 1 else None
    body = []
    for t in techs:
        rs = by[t]
        body.append(f"        {TECH_NAMES.get(t, t)} & {n(rs, 'functional_pass')} & {n(rs, 'cwe_fixed')} & "
                    f"{n(rs, 'safety_violation_introduced')} & {n(rs, 'joint_success')} & {n(rs, 'tool_disagree')} \\\\")
    cap_n = f"$n={n_per}$ per technique" if n_per else "counts per technique"
    return "\n".join([
        r"\begin{table}[t]",
        r"    \centering",
        f"    \\caption{{Results by technique (both models and domains, {cap_n})}}",
        r"    \label{tab:technique}",
        r"    \footnotesize",
        r"    \resizebox{\linewidth}{!}{%",
        r"    \begin{tabular}{|l|c|c|c|c|c|}",
        r"        \hline",
        r"        \textbf{Technique} & \textbf{Functional} & \textbf{CWE fixed} & \textbf{Safety viol.} & \textbf{Joint} & \textbf{Disagree} \\",
        r"        \hline", *body, r"        \hline",
        f"        All ($n={len(rows)}$) & {n(rows, 'functional_pass')} & {n(rows, 'cwe_fixed')} & "
        f"{n(rows, 'safety_violation_introduced')} & {n(rows, 'joint_success')} & {n(rows, 'tool_disagree')} \\\\",
        r"        \hline",
        r"    \end{tabular}}",
        r"\end{table}", ""])


def model_table(rows):
    by = defaultdict(list)
    for r in rows:
        by[(r["model"], r["technique"])].append(r)
    models = sorted({r["model"] for r in rows}, key=lambda m: (m != "qwen2.5-coder:32b", m))
    techs = sorted({r["technique"] for r in rows})
    sizes = {len(v) for v in by.values()}
    cap_n = f"$n={sizes.pop()}$ each" if len(sizes) == 1 else "counts"
    body = []
    for m in models:
        for i, t in enumerate(techs):
            rs = by.get((m, t), [])
            name = MODEL_NAMES.get(m, m.replace("_", r"\_")) if i == 0 else ""
            body.append(f"        {name} & {t} & {n(rs, 'extracted')} & {n(rs, 'build_ok')} & {n(rs, 'cwe_fixed')} & "
                        f"{n(rs, 'safety_violation_introduced')} & {n(rs, 'joint_success')} \\\\")
        body.append(r"        \hline")
    return "\n".join([
        r"\begin{table}[t]",
        r"    \centering",
        f"    \\caption{{Results by model and technique ({cap_n})}}",
        r"    \label{tab:model}",
        r"    \footnotesize",
        r"    \resizebox{\linewidth}{!}{%",
        r"    \begin{tabular}{|l|l|c|c|c|c|c|}",
        r"        \hline",
        r"        \textbf{Model} & \textbf{Tech.} & \textbf{Extr.} & \textbf{Builds} & \textbf{Fixed} & \textbf{Safety} & \textbf{Joint} \\",
        r"        \hline", *body,
        r"    \end{tabular}}",
        r"\end{table}", ""])


def task_table(rows, cfg):
    by = defaultdict(list)
    for r in rows:
        by[(r["task"], r["technique"])].append(r)
    tasks = sorted({r["task"] for r in rows}, key=lambda t: (t[0], int(t[1:])))
    techs = sorted({r["technique"] for r in rows})
    sizes = {len(v) for v in by.values()}
    cap_n = f"out of {sizes.pop()} per cell" if len(sizes) == 1 else "counts per cell"
    body, prev_domain = [], None
    for t in tasks:
        info = cfg["by_id"].get(t, {})
        dom = info.get("domain", "")
        if prev_domain and dom != prev_domain:
            body.append(r"        \hline")
        prev_domain = dom
        cells = []
        for tech in techs:
            rs = by.get((t, tech), [])
            cells.append(f"{n(rs, 'cwe_fixed')} / {n(rs, 'safety_violation_introduced')} / {n(rs, 'joint_success')}")
        body.append(f"        {t} & {dom} & {info.get('representation', '')} & {info.get('seed_type', '')} & "
                    + " & ".join(cells) + r" \\")
    cols = "|c|l|l|l|" + "c|" * len(techs)
    heads = " & ".join(rf"\textbf{{{TECH_NAMES.get(t, t)}}}" for t in techs)
    return "\n".join([
        r"\begin{table*}[t]",
        r"    \centering",
        f"    \\caption{{Results by task and technique: patches that fixed the CWE / introduced a safety violation / achieved joint success, {cap_n}}}",
        r"    \label{tab:task}",
        r"    \footnotesize",
        f"    \\begin{{tabular}}{{{cols}}}",
        r"        \hline",
        rf"        \textbf{{Task}} & \textbf{{Domain}} & \textbf{{Repr.}} & \textbf{{Seed type}} & {heads} \\",
        r"        \hline", *body, r"        \hline",
        r"    \end{tabular}",
        r"\end{table*}", ""])


def macros(rows, base):
    s = {}
    ext = [r for r in rows if truthy(r["extracted"])]
    fixed = n(rows, "cwe_fixed")
    fixed_unsafe = sum(truthy(r["cwe_fixed"]) and truthy(r["safety_violation_introduced"]) for r in rows)
    s.update({"patches": len(rows), "extracted": len(ext), "built": n(rows, "build_ok"),
              "fixed": fixed, "fixed-pct": pct(fixed, len(rows)),
              "functional": n(rows, "functional_pass"),
              "safety": n(rows, "safety_violation_introduced"),
              "joint": n(rows, "joint_success"), "joint-pct": pct(n(rows, "joint_success"), len(rows)),
              "fixed-unsafe": fixed_unsafe, "fixed-unsafe-pct": pct(fixed_unsafe, fixed),
              "disagree": n(ext, "tool_disagree"), "disagree-pct": pct(n(ext, "tool_disagree"), len(ext)),
              "sec-ok-safety-bad": sum(truthy(r["tool_sec_ok"]) and not truthy(r["tool_safety_ok"]) for r in ext),
              "safety-ok-sec-bad": sum(truthy(r["tool_safety_ok"]) and not truthy(r["tool_sec_ok"]) for r in ext)})
    rule_cols = [c for c in rows[0] if c.startswith("misra_") and c.endswith("_new")]
    for c in rule_cols:
        rule = c.replace("misra_", "").replace("_new", "").replace("_", ".")
        vals = [int(r[c] or 0) for r in rows]
        s[f"rule{rule}-patches"] = sum(v > 0 for v in vals)
        s[f"rule{rule}-violations"] = sum(vals)
    for key, field in (("tech", "technique"), ("model", "model"), ("domain", "domain"),
                       ("seed", "seed_type"), ("repr", "representation")):
        groups = defaultdict(list)
        for r in rows:
            if r.get(field):
                groups[r[field]].append(r)
        for g, rs in groups.items():
            g = g.replace(":", "-")
            for m, col in (("fixed", "cwe_fixed"), ("safety", "safety_violation_introduced"),
                           ("joint", "joint_success"), ("functional", "functional_pass")):
                s[f"{g}-{m}"] = n(rs, col)
                s[f"{g}-{m}-pct"] = pct(n(rs, col), len(rs))
            s[f"{g}-n"] = len(rs)
    if base:
        s["seeded-flagged"] = sum(1 for b in base.values() if b["seeded"]["sec_warnings"])
        s["tasks"] = len(base)
        s["upstream-fixes-violating"] = sum(1 for b in base.values() if b.get("upstream_fix_introduces_misra"))
    lines = [r"\makeatletter"]
    for k in sorted(s):
        lines.append(rf"\expandafter\def\csname stat@{k}\endcsname{{{s[k]}}}")
    lines += [r"\makeatother",
              r"% \stat{key}: prints the value, or a red ?key? if the key does not exist",
              r"\providecommand{\stat}[1]{\ifcsname stat@#1\endcsname\csname stat@#1\endcsname"
              r"\else\textcolor{red}{?#1?}\fi}", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", default="base")
    ap.add_argument("--out", default=str(ROOT / "paper" / "tables"))
    args = ap.parse_args()
    src = RESULTS / args.tag
    if not (src / "results.csv").exists():
        raise SystemExit(f"{src}/results.csv not found; run eval.py --tag {args.tag} first")
    with open(src / "results.csv") as f:
        rows = [r for r in csv.DictReader(f) if r["model"] not in EXCLUDE_MODELS]
    base = json.loads((src / "baselines.json").read_text()) if (src / "baselines.json").exists() else {}
    cfg = load_config()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    rel = f"results/{args.tag}"
    files = {"technique.tex": technique_table(rows), "model.tex": model_table(rows),
             "task.tex": task_table(rows, cfg), "macros.tex": macros(rows, base)}
    if base:
        files["baseline.tex"] = baseline_table(base)
    for name, body in files.items():
        (out / name).write_text(header(rel) + body)
    print(f"{len(rows)} patches from {rel} -> {out.relative_to(ROOT) if out.is_relative_to(ROOT) else out}/"
          f" ({', '.join(sorted(files))})")


if __name__ == "__main__":
    main()
